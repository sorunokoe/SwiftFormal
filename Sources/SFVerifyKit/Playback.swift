import Foundation
import SFSIL

// Concrete playback (plan item U5): each counterexample with a `replay` (a free function over scalars, or a trap in a
// method or getter whose values are Swift literals, `PlaybackLiterals.swift`) becomes a Swift Testing test
// that runs the compiled function on it (`sfverify --emit-tests`), and `--confirm` runs those tests, so the model's
// answer is checked against the real binary. A counterexample that does not reproduce is a disagreement between the
// model and the compiler: the function becomes an `internalError`.

/// One generated test.
package struct PlaybackTest: Sendable, Equatable {
    /// The test function's name, unique in the file (`playback_3_percent`).
    package var name: String
    /// The symbol of the function it replays.
    package var symbol: String
    /// The function's display name.
    package var function: String
    /// True when the counterexample holds only without asserts (`-assert-config Release`, `-O`): the test is compiled
    /// in release builds only (`#if !DEBUG`).
    package var releaseOnly: Bool
    /// The test's source.
    package var source: String
}

/// Writing and running the playback tests of a report.
package enum Playback {
    /// The test file's name for `module`.
    package static func fileName(module: String) -> String { "\(module)ScanPlaybackTests.swift" }

    /// The tests for `report`, and a line for each counterexample that has none (and why).
    package static func tests(for report: ScanReport) -> (tests: [PlaybackTest], skipped: [String]) {
        var tests: [PlaybackTest] = []
        var skipped: [String] = []
        let releaseReport = report.configurations == ["release"] || report.optimization == "-O"
        for f in report.functions where f.status == .mayTrap || f.status == .contractFails {
            guard let e = f.counterexample else { continue }
            guard e.replay != nil else {
                skipped.append("\(f.name): no replay (\(e.noReplay ?? "inputs that are not integers, Bool or literal values"))")
                continue
            }
            if let why = uncallable(f) {
                skipped.append("\(f.name): \(why)")
                continue
            }
            switch test(function: f.name, symbol: f.symbol, e, index: tests.count + 1, releaseReport: releaseReport) {
            case .success(let test): tests.append(test)
            case .failure(let why): skipped.append("\(f.name): \(why.description)")
            }
        }
        return (tests, skipped)
    }

    /// Why a counterexample has no playback test.
    package struct NoTest: Error, CustomStringConvertible {
        package var description: String
    }

    /// The test that replays counterexample `e` of `function` (its display name, and `symbol`), named
    /// `playback_<index>_<name>`. `releaseReport`: the report holds only without asserts, so the test is release-only
    /// whatever the failure says.
    package static func test(
        function: String, symbol: String, _ e: ScanCounterexample, index: Int, releaseReport: Bool = false
    ) -> Result<PlaybackTest, NoTest> {
        guard let call = e.replay else {
            return .failure(NoTest(description: "no replay (\(e.noReplay ?? "inputs that are not integers, Bool or literal values"))"))
        }
        let releasePrefix = "in a release build (-assert-config Release): "
        let releaseOnly = releaseReport || e.failure.hasPrefix(releasePrefix)
        let failure = e.failure.hasPrefix(releasePrefix) ? String(e.failure.dropFirst(releasePrefix.count)) : e.failure
        let name = "playback_\(index)_" + identifier(function)
        let title = "\(function) \(failure) when \(e.inputs.joined(separator: ", "))"
        let body: String
        if let ensures = e.ensuresCall {
            body = """
                @Test(\(literal(title))) func \(name)() {
                    #expect(!\(ensures))
                }
                """
        } else if isTrap(failure, e) {
            body = """
                @Test(\(literal(title))) func \(name)() async {
                    await #expect(processExitsWith: .failure) { _ = \(call) }
                }
                """
        } else {
            return .failure(NoTest(description: "\(failure) (not a trap or a postcondition a test can check)"))
        }
        let source = releaseOnly ? "#if !DEBUG  // reproduces without asserts: swift test -c release\n\(body)\n#endif" : body
        return .success(PlaybackTest(name: name, symbol: symbol, function: function, releaseOnly: releaseOnly, source: source))
    }

    /// The test file: a header, the tests, and the skipped counterexamples as comments.
    package static func file(for report: ScanReport) -> String {
        let (tests, skipped) = tests(for: report)
        var lines = [
            "// Generated by `sfverify --emit-tests` from the SIL of \(report.module)\(report.compiler.map { " (\($0))" } ?? "").",
            "// Each test replays one counterexample on the compiled code and passes while it still reproduces: a trap",
            "// ends the process (an exit test), a broken postcondition returns false. Once a function is fixed its test",
            "// fails; delete it then. Exit tests need Swift 6.3 or newer on macOS or Linux.",
            "",
            "#if (os(macOS) || os(Linux)) && compiler(>=6.3)",
            "import Testing",
            "@testable import \(report.module)",
            "",
        ]
        for test in tests { lines += [test.source, ""] }
        lines.append("#endif")
        if !skipped.isEmpty {
            lines.append("")
            lines.append("// No test for:")
            lines += skipped.map { "//   \($0)" }
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// True for a failure that is a trap of the function itself (not undefined behaviour, a spec's own trap, or a
    /// counterexample that could not be replayed).
    private static func isTrap(_ failure: String, _ e: ScanCounterexample) -> Bool {
        guard e.result == nil else { return false }
        let notTraps = ["undefined behaviour", "could not replay", "the requires function", "the ensures function", "the claim fails"]
        return !notTraps.contains { failure.hasPrefix($0) }
    }

    /// Why a test cannot call `f` as `replay` writes it, read from its declaration: `private` (out of reach of
    /// `@testable import`), an `inout` parameter, or `throws`/`async`. Nil when it can, or the source is not readable.
    package static func uncallable(_ f: FunctionReport) -> String? {
        guard let location = f.location, let text = try? String(contentsOfFile: location.file, encoding: .utf8) else { return nil }
        return uncallable(declaredAt: location.line, in: text)
    }

    /// `uncallable(_:)` for the declaration at `line` (1-based) of the source `text`.
    package static func uncallable(declaredAt line: Int, in text: String) -> String? {
        let lines = text.components(separatedBy: "\n").dropFirst(max(line - 1, 0))
        var declaration = ""
        for line in lines.prefix(12) {
            declaration += " " + line
            if line.contains("{") { break }
        }
        let head = declaration.components(separatedBy: "{")[0]
        let words = Set(head.split { !$0.isLetter && !$0.isNumber && $0 != "_" }.map(String.init))
        if words.contains("private") || words.contains("fileprivate") { return "private (a test cannot call it)" }
        if words.contains("inout") { return "an inout parameter (the replay passes a value)" }
        if words.contains("throws") || words.contains("rethrows") || words.contains("async") { return "throws or async" }
        return nil
    }

    /// `percent` for `percent(_:_:)`, with anything that is not a letter, digit or `_` replaced.
    private static func identifier(_ name: String) -> String {
        let base = name.prefix { $0 != "(" }
        return String(base.map { $0.isLetter || $0.isNumber || $0 == "_" ? $0 : "_" })
    }

    /// A Swift string literal of `text`.
    private static func literal(_ text: String) -> String {
        "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
    }

    // MARK: confirming

    /// The report with each counterexample in `outcomes` (by symbol) marked `confirmed`. One that did not reproduce
    /// turns its function into an `internalError` (the model and the compiler disagree); the summary is recounted.
    package static func confirming(_ report: ScanReport, _ outcomes: [String: Bool]) -> ScanReport {
        let functions = report.functions.map { f -> FunctionReport in
            guard let reproduced = outcomes[f.symbol], var e = f.counterexample else { return f }
            var f = f
            e.confirmed = reproduced
            f.counterexample = e
            if !reproduced {
                f.detail =
                    "the counterexample did not reproduce in a native build (\(f.status == .mayTrap ? "no trap" : "the contract held")): "
                    + "the model and the compiler disagree; please report this"
                f.status = .internalError
            }
            return f
        }
        var confirmed = ScanReport(
            module: report.module, optimization: report.optimization, functions: functions,
            compilerGenerated: report.summary.compilerGenerated, timing: report.timing)
        confirmed.configurations = report.configurations
        confirmed.compiler = report.compiler
        confirmed.pinned = report.pinned
        return confirmed
    }

    /// Why `--confirm` could not run the tests.
    package struct ConfirmError: Error, CustomStringConvertible {
        package var description: String
    }

    /// What `--confirm` found: whether each counterexample reproduced, by symbol, and whether the scratch build had
    /// the scan's settings (`exact`). Without them a counterexample that did not reproduce proves nothing.
    package struct Confirmation: Sendable, Equatable {
        package var outcomes: [String: Bool]
        package var exact: Bool

        package init(outcomes: [String: Bool], exact: Bool) {
            self.outcomes = outcomes
            self.exact = exact
        }
    }

    /// Settings of the scratch build: compiler arguments to forward, the language mode (`5`, `6`), and whether they
    /// cover every argument the scan used.
    package struct BuildSettings: Sendable, Equatable {
        package var swiftc: [String]
        package var languageMode: String
        package var exact: Bool
    }

    /// How the scratch package must build to compile what the scan read: `-D` conditions and feature flags to
    /// forward, the language mode, and whether that covers every scan argument (`exact`). SwiftPM's debug build also
    /// defines `DEBUG` and `SWIFT_PACKAGE`; when the scan did not and a source has `#if`, the build may differ.
    package static func buildSettings(
        arguments: [String], sources: [String]
    ) -> BuildSettings {
        let harmless: Set = [
            "-I", "-F", "-L", "-package-name", "-target", "-sdk", "-module-cache-path", "-module-name", "-j",
            "-resource-dir",
        ]
        let alone: Set = ["-g", "-Onone", "-enable-testing", "-parse-as-library", "-DSWIFT_PACKAGE", "-DDEBUG"]
        var swiftc: [String] = []
        var defines: Set<String> = []
        var mode = "5"
        var exact = true
        var rest = arguments[...]
        while let argument = rest.popFirst() {
            if argument == "-D", let name = rest.popFirst() {
                defines.insert(name)
                swiftc += ["-D", name]
            } else if argument.hasPrefix("-D") {
                defines.insert(String(argument.dropFirst(2)))
                if !alone.contains(argument) { swiftc.append(argument) }
            } else if argument == "-enable-experimental-feature" || argument == "-enable-upcoming-feature", let name = rest.popFirst() {
                swiftc += [argument, name]
            } else if argument == "-swift-version", let version = rest.popFirst() {
                mode = version
            } else if harmless.contains(argument) {
                _ = rest.popFirst()
            } else if !alone.contains(argument) {
                exact = false
            }
        }
        let conditional = sources.contains { (try? String(contentsOfFile: $0, encoding: .utf8))?.contains("#if") ?? true }
        if conditional && !defines.isSuperset(of: ["DEBUG", "SWIFT_PACKAGE"]) { exact = false }
        return BuildSettings(swiftc: swiftc, languageMode: mode, exact: exact)
    }

    /// Builds the module from `files` with the tests in a scratch package and runs each debug test alone (a release-only
    /// one is not run). `arguments` are the scan's extra compiler arguments (see `buildSettings`).
    package static func confirm(_ report: ScanReport, files: [String], arguments: [String], swift: String) throws -> Confirmation {
        let tests = tests(for: report).tests.filter { !$0.releaseOnly }
        let settings = buildSettings(arguments: arguments, sources: files)
        guard !tests.isEmpty else { return Confirmation(outcomes: [:], exact: settings.exact) }
        let root = NSTemporaryDirectory() + "sfverify-confirm-\(UUID().uuidString)"
        defer { try? FileManager.default.removeItem(atPath: root) }
        let manager = FileManager.default
        let sources = root + "/Sources/" + report.module
        let testDirectory = root + "/Tests/PlaybackTests"
        try manager.createDirectory(atPath: sources, withIntermediateDirectories: true)
        try manager.createDirectory(atPath: testDirectory, withIntermediateDirectories: true)
        for (index, file) in files.enumerated() {
            try manager.copyItem(atPath: file, toPath: sources + "/\(index)_" + (file as NSString).lastPathComponent)
        }
        let mode = settings.languageMode == "5" ? ".v5" : settings.languageMode == "6" ? ".v6" : ".version(\"\(settings.languageMode)\")"
        try """
        // swift-tools-version: 6.0
        import PackageDescription
        let package = Package(
            name: "Playback",
            platforms: [.macOS(.v13)],
            targets: [
                .target(name: "\(report.module)"),
                .testTarget(name: "PlaybackTests", dependencies: ["\(report.module)"]),
            ],
            swiftLanguageModes: [\(mode)]
        )
        """.write(toFile: root + "/Package.swift", atomically: true, encoding: .utf8)
        try file(for: report).write(toFile: testDirectory + "/" + fileName(module: report.module), atomically: true, encoding: .utf8)

        let forwarded = settings.swiftc.flatMap { ["-Xswiftc", $0] }
        let build = try run(swift, ["build", "--build-tests", "--package-path", root] + forwarded)
        guard build.status == 0 else {
            throw ConfirmError(description: "the playback package did not build:\n" + build.output.suffix(2000))
        }
        var outcomes: [String: Bool] = [:]
        for test in tests {
            let result = try run(swift, ["test", "--skip-build", "--package-path", root, "--filter", "\(test.name)\\("] + forwarded)
            guard result.output.contains("Test run with 1 test") else {
                throw ConfirmError(description: "\(test.name) did not run exactly once:\n" + result.output.suffix(2000))
            }
            outcomes[test.symbol] = result.status == 0
        }
        return Confirmation(outcomes: outcomes, exact: settings.exact)
    }

    /// The report with `confirmation` applied, and the names of the functions whose counterexample did not reproduce
    /// in a scratch build that may differ from the scan's (left unmarked: that proves nothing either way).
    package static func settle(_ report: ScanReport, _ confirmation: Confirmation) -> (report: ScanReport, inconclusive: [String]) {
        guard !confirmation.exact else { return (confirming(report, confirmation.outcomes), []) }
        let failed = Set(confirmation.outcomes.filter { !$0.value }.keys)
        let names = report.functions.filter { failed.contains($0.symbol) }.map(\.name)
        return (confirming(report, confirmation.outcomes.filter { $0.value }), names)
    }

    private static func run(_ executable: String, _ arguments: [String]) throws -> (status: Int32, output: String) {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: executable)
        process.arguments = arguments
        let pipe = Pipe()
        process.standardOutput = pipe
        process.standardError = pipe
        try process.run()
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        return (process.terminationStatus, String(bytes: data, encoding: .utf8) ?? "")
    }

    /// The `swift` driver next to the compiler a scan uses, or `xcrun --find swift`'s.
    package static func swiftDriver() throws -> String {
        let swiftc = try ScanToolchain.current().swiftc
        let next = (swiftc as NSString).deletingLastPathComponent + "/swift"
        return FileManager.default.isExecutableFile(atPath: next) ? next : "/usr/bin/swift"
    }
}

extension Verifier {
    /// `spec(inputs…, call)` for an `_ensures` function `spec` over the scalar inputs of a replayable call; nil
    /// when there is no `call` or an input is not a scalar.
    static func ensuresCall(_ values: [UInt64], spec: FunctionInfo, types: [String?], call: String?) -> String? {
        guard let call, values.count == types.count else { return nil }
        var arguments: [String] = []
        for (value, type) in zip(values, types) {
            guard let type else { return nil }
            arguments.append(render(value, type: type, width: bitWidth(type)))
        }
        arguments.append(call)
        let labels = spec.argumentLabels
        let labelled = arguments.enumerated().map { i, text in i < labels.count && labels[i] != "_" ? "\(labels[i]): \(text)" : text }
        return "\(spec.baseName)(\(labelled.joined(separator: ", ")))"
    }
}
