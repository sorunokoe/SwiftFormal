import Foundation

extension BinaryDomainBuilder {
    // MARK: Field types

    func domain(of spelling: TypeSpelling) -> Result<Built, Failure> {
        switch spelling {
        case .unsupported(let reason): return .failure(Failure(reason))
        case .optional(let wrapped):
            return domain(of: wrapped).map { inner in
                let swiftType = "\(inner.swiftType)?"
                return Built(
                    expression: "SwiftFormal.Domain<\(swiftType)>.optional(\(inner.expression))", swiftType: swiftType,
                    sampled: inner.sampled)
            }
        case .array(let element):
            return domain(of: element).map { inner in
                let swiftType = "[\(inner.swiftType)]"
                return Built(
                    expression:
                        "SwiftFormal.Domain<\(swiftType)>.arrays(of: \(inner.expression).evenlySpaced(3), maxLength: 2).asSample",
                    swiftType: swiftType, sampled: ["arrays"])
            }
        case .existential(let name):
            guard module.types[name]?.kind == .protocolType else { return .failure(Failure("no domain for any \(name)")) }
            return named(name)
        case .named(let name):
            if let scalar = scalar(name) { return .success(scalar) }
            if module.types[name] == nil, let aliased = module.aliases[name], !inProgress.contains("alias \(name)") {
                inProgress.insert("alias \(name)")
                defer { inProgress.remove("alias \(name)") }
                return domain(of: TypeSpelling.parse(aliased))
            }
            guard module.types[name] != nil else { return .failure(Failure("no domain for \(name)")) }
            return named(name)
        }
    }

    func scalar(_ name: String) -> Built? {
        if name == "Bool" { return Built(expression: "SwiftFormal.Domain<Bool>.bool", swiftType: name, sampled: []) }
        if BinaryDomainWriter.integers.contains(name) {
            let values = name.hasPrefix("U") ? "[0, 1, .max]" : "[.min, -1, 0, 1, .max]"
            return Built(expression: "SwiftFormal.Domain<\(name)>.samples(\(values))", swiftType: name, sampled: [name])
        }
        if BinaryDomainWriter.floats.contains(name) {
            let values =
                "[-.infinity, -.greatestFiniteMagnitude, -1, -0.0, 0, .leastNonzeroMagnitude, 1, .greatestFiniteMagnitude, .infinity, .nan]"
            return Built(expression: "SwiftFormal.Domain<\(name)>.samples(\(values))", swiftType: name, sampled: [name])
        }
        if name == "String" {
            return Built(expression: #"SwiftFormal.Domain<String>.samples(["", "a", "Ünïcødé ✓"])"#, swiftType: name, sampled: [name])
        }
        return nil
    }

    // MARK: Names

    func memberName(for name: String) -> String {
        var base = lowerCamel(name.replacingOccurrences(of: ".", with: ""))
        if BinaryDomainWriter.reservedMembers.contains(base) || BinaryDomainWriter.keywords.contains(base) { base += "Values" }
        var candidate = base
        var number = 2
        while usedMembers.contains(candidate) {
            candidate = "\(base)\(number)"
            number += 1
        }
        usedMembers.insert(candidate)
        return candidate
    }

    func lowerCamel(_ name: String) -> String {
        let characters = Array(name)
        var upper = 0
        while upper < characters.count, characters[upper].isUppercase { upper += 1 }
        if upper == 0 { return name }
        // `URLRequest` becomes `urlRequest`: an initial run of capitals keeps its last letter for the next word.
        let lowered = upper == characters.count || upper == 1 ? upper : upper - 1
        return String(characters[..<lowered]).lowercased() + String(characters[lowered...])
    }

    func identifier(_ name: String) -> String { name.replacingOccurrences(of: ".", with: "_") }

    func escaped(_ name: String) -> String { BinaryDomainWriter.keywords.contains(name) ? "`\(name)`" : name }

    func labels(_ parameters: [TypeParam]) -> String { parameters.map { "\($0.label ?? "_"):" }.joined() }

    // MARK: Output

    func result(imports: [String]) -> BinaryDomainResult {
        var lines = [
            "// swift-format-ignore-file",
            "// Generated by sfgen domains; do not edit. Regenerate when the framework changes.",
            "//",
            "// Walk domains for the types of \(module.name). A domain marked exhaustive lists every value of its type, so",
            "// a walk over it can prove; a bounded one samples numbers, strings or arrays, so walks over it are bounded.",
            "",
        ]
        let modules = (["SwiftFormal", module.name] + imports).reduce(into: [String]()) { if !$0.contains($1) { $0.append($1) } }
        lines += modules.sorted().map { "import \($0)" }
        for name in bodies.keys.sorted() {
            guard let generated = bodies[name], let member = generated.entry.member else { continue }
            let (swiftType, body, entry) = (generated.swiftType, generated.body, generated.entry)
            lines.append("")
            lines.append("extension SwiftFormal.Domain where Value == \(swiftType) {")
            let reasons = entry.reason.components(separatedBy: "; ")
            var note = "bounded (\(reasons.prefix(3).joined(separator: "; "))\(reasons.count > 3 ? "; …" : ""))"
            if entry.status == .exhaustive {
                note =
                    entry.category == .enumeration
                    ? "exhaustive when allCases lists every case, which it checks; a sample otherwise" : "exhaustive"
            }
            lines.append("    /// \(entry.category.rawValue): \(note).")
            lines.append("    static var \(member): Self {")
            for line in body.split(separator: "\n", omittingEmptySubsequences: false) { lines.append("        \(line)") }
            lines.append("    }")
            lines.append("}")
        }
        for base in caseChecks.keys.sorted() {
            guard let check = caseChecks[base] else { continue }
            lines.append("")
            lines.append("// Stops compiling when the type gains or loses a case: regenerate this file then.")
            lines.append(check)
        }
        return BinaryDomainResult(
            source: lines.joined(separator: "\n") + "\n", entries: entries.keys.sorted().compactMap { entries[$0] })
    }
}
