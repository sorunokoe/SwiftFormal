/// Pretty-prints a `SpecModule` as a self-contained Lean 4 file (core Lean only, no Mathlib).
public enum LeanEmitter {
    public static func emit(_ module: SpecModule) -> String {
        var out = "-- Generated by FormalSpec from Swift. Do not edit by hand.\n"
        out += "namespace \(module.name)\n\n"
        for decl in module.declarations {
            out += emit(decl, in: module) + "\n\n"
        }
        out += "end \(module.name)\n"
        return out
    }

    static func emit(_ decl: Declaration, in module: SpecModule) -> String {
        switch decl {
        case let .function(name, params, returns, body):
            let ps = params.map { "(\($0.name) : \($0.type.lean))" }.joined(separator: " ")
            return "def \(name) \(ps) : \(returns.lean) :=\n  \(expr(body, module: module, asProp: false))"
        case let .theorem(name, binders, statement, proof):
            let bs = binders.map { "(\($0.name) : \($0.type.lean))" }.joined(separator: " ")
            return "theorem \(name) \(bs) :\n    \(expr(statement, module: module, asProp: true)) := \(withUnfolding(proof, module: module))"
        }
    }

    /// `by grind` alone does not unfold user definitions; pass them as hints.
    static func withUnfolding(_ proof: String, module: SpecModule) -> String {
        guard proof == "by grind" else { return proof }
        let names = module.declarations.compactMap { decl -> String? in
            if case let .function(name, _, _, _) = decl { return name } else { return nil }
        }
        return names.isEmpty ? proof : "by grind [\(names.joined(separator: ", "))]"
    }

    /// `asProp` chooses between Lean's `Prop` connectives (∧ ∨ ¬ → =) used in
    /// theorem statements, and `Bool` operators (&& || ! ==) used in code.
    static func expr(_ e: Expr, module: SpecModule, asProp: Bool) -> String {
        func r(_ x: Expr) -> String { expr(x, module: module, asProp: asProp) }
        switch e {
        case let .variable(n): return n
        case let .natLiteral(v): return "\(v)"
        case let .boolLiteral(b): return b ? "true" : "false"
        case let .add(a, b): return "(\(r(a)) + \(r(b)))"
        case let .sub(a, b): return "(\(r(a)) - \(r(b)))"
        case let .mul(a, b): return "(\(r(a)) * \(r(b)))"
        case let .div(a, b): return "(\(r(a)) / \(r(b)))"
        case let .min(a, b): return "(min \(r(a)) \(r(b)))"
        case let .le(a, b): return asProp ? "(\(r(a)) ≤ \(r(b)))" : "decide (\(r(a)) ≤ \(r(b)))"
        case let .lt(a, b): return asProp ? "(\(r(a)) < \(r(b)))" : "decide (\(r(a)) < \(r(b)))"
        case let .eq(a, b): return asProp ? "(\(r(a)) = \(r(b)))" : "(\(r(a)) == \(r(b)))"
        case let .and(a, b): return asProp ? "(\(r(a)) ∧ \(r(b)))" : "(\(r(a)) && \(r(b)))"
        case let .or(a, b): return asProp ? "(\(r(a)) ∨ \(r(b)))" : "(\(r(a)) || \(r(b)))"
        case let .not(a): return asProp ? "¬\(r(a))" : "!\(r(a))"
        case let .implies(a, b): return "(\(r(a)) → \(r(b)))"
        case let .ifThenElse(c, t, f):
            // Conditions are always emitted as Props; Lean decides them.
            let cond = expr(c, module: module, asProp: true)
            return "(if \(cond) then \(r(t)) else \(r(f)))"
        case let .call(name, args):
            let call = ([name] + args.map { expr($0, module: module, asProp: false) }).joined(separator: " ")
            if asProp, returnType(of: name, in: module) == .bool { return "((\(call)) = true)" }
            return "(\(call))"
        }
    }

    static func returnType(of name: String, in module: SpecModule) -> SpecType? {
        for case let .function(n, _, returns, _) in module.declarations where n == name { return returns }
        return nil
    }
}
